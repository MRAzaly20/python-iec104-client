class CommandSender:
    """
    IEC 104 Command Sender with Select-Before-Operate (SBO) support.
    
    IEC 104 defines two command modes:
    
    1. DIRECT EXECUTE (DE):
       - Client sends command with COT=ACTIVATION
       - Server immediately executes and confirms
       - Simple, fast, but less safe for critical operations
    
    2. SELECT-BEFORE-OPERATE (SBO):
       - Phase 1: Client sends SELECT (S/E bit = 0, COT=ACTIVATION)
       - Phase 2: Server confirms SELECT (COT=ACTIVATION_CON)
       - Phase 3: Client sends EXECUTE (S/E bit = 1, COT=ACTIVATION)
       - Phase 4: Server executes and confirms (COT=ACTIVATION_CON)
       
       If SELECT is negatively confirmed, operation is cancelled.
       SBO provides safety for critical operations (breakers, valves).
    
    Flowchart:
    ┌─────────────────────────────────────────────────────────────┐
    │                    sendCommandSBO()                         │
    └───────────────────────────┬─────────────────────────────────┘
                                │
                                ▼
                ┌───────────────────────────────┐
                │  Build Command with SELECT    │
                │  (S/E = 0, COT = ACTIVATION)  │
                └───────────────────────────────┘
                                │
                                ▼
                ┌───────────────────────────────┐
                │     Transmit SELECT           │
                └───────────────────────────────┘
                                │
                                ▼
                ┌───────────────────────────────┐
                │  Wait for ACTIVATION_CON      │
                │  (with timeout)               │
                └───────────────────────────────┘
                                │
                    ┌───────────┴───────────┐
                    ▼                       ▼
            ┌───────────────┐       ┌───────────────┐
            │  Positive     │       │  Negative or  │
            │  Confirmation │       │  Timeout      │
            └───────┬───────┘       └───────┬───────┘
                    │                       │
                    ▼                       ▼
        ┌───────────────────────┐   ┌───────────────────┐
        │ Build Command EXECUTE │   │  CANCEL Operation │
        │ (S/E = 1, same params)│   │  Return FAILURE   │
        └───────────────────────┘   └───────────────────┘
                    │
                    ▼
        ┌───────────────────────┐
        │   Transmit EXECUTE    │
        └───────────────────────┘
                    │
                    ▼
        ┌───────────────────────┐
        │ Wait for EXECUTE_CON  │
        └───────────────────────┘
                    │
                    ▼
        ┌───────────────────────┐
        │    Return SUCCESS     │
        └───────────────────────┘
    """
    
    def __init__(self, config: CommandSenderConfig,
                 station: c104.Station,
                 on_log: Optional[Callable[[str, str], None]] = None):
        self.config = config
        self.station = station
        self.on_log = on_log
        
        # Track pending confirmations
        self._pending_select: Optional[asyncio.Future] = None
        self._pending_execute: Optional[asyncio.Future] = None
        self._last_command_result: Optional[bool] = None
        
    def _log(self, msg: str, level: str = "INFO"):
        """Log message if callback available."""
        if self.on_log:
            self.on_log(msg, level)
            
    async def send_command_direct(self, point: c104.Point, state, 
                                   qualifier=None) -> CommandResult:
        """
        Send command using Direct Execute mode.
        
        Args:
            point: The command point to send.
            state: Command state (e.g., c104.Double.ON).
            qualifier: Optional command qualifier.
            
        Returns:
            CommandResult indicating success or failure.
        """
        try:
            self._log(f"[DirectExecute] Sending command IOA {point.io_address}: {state}", "COMMAND")
            
            # Build command info
            if qualifier is None:
                qualifier = c104.Qoc.SHORT_PULSE
                
            point.info = c104.DoubleCmd(
                state=state,
                qualifier=qualifier
            )
            
            # Transmit with ACTIVATION cause
            if point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[DirectExecute] Command sent successfully", "SUCCESS")
                return CommandResult.SUCCESS
            else:
                self._log(f"[DirectExecute] Command transmission failed", "ERROR")
                return CommandResult.ERROR
                
        except Exception as e:
            self._log(f"[DirectExecute] Error: {str(e)}", "ERROR")
            return CommandResult.ERROR
    
    async def send_command_sbo(self, point: c104.Point, state,
                                qualifier=None) -> CommandResult:
        """
        Send command using Select-Before-Operate (SBO) mode.
        
        This implements the two-phase SBO handshake:
        1. Send SELECT command and wait for positive confirmation
        2. If confirmed, send EXECUTE command
        3. If negatively confirmed or timeout, cancel operation
        
        Args:
            point: The command point to send.
            state: Command state (e.g., c104.Double.ON).
            qualifier: Optional command qualifier.
            
        Returns:
            CommandResult indicating success or failure.
            
        Pseudocode:
            function sendCommandSBO(point, state):
                # Phase 1: SELECT
                selectCmd = buildCommand(point, state, SELECT=True)
                send(selectCmd)
                
                confirmation = waitForConfirmation(timeout=SBO_TIMEOUT)
                
                if confirmation == NEGATIVE or confirmation == TIMEOUT:
                    log("SELECT rejected or timed out")
                    return FAILURE
                
                # Phase 2: EXECUTE
                executeCmd = buildCommand(point, state, SELECT=False)
                send(executeCmd)
                
                execConfirm = waitForConfirmation(timeout=EXECUTE_TIMEOUT)
                
                if execConfirm == SUCCESS:
                    return SUCCESS
                else:
                    return FAILURE
        """
        try:
            self._log(f"[SBO] Starting Select-Before-Operate for IOA {point.io_address}", "COMMAND")
            
            # === PHASE 1: SELECT ===
            self._log(f"[SBO] Phase 1: Sending SELECT (S/E=0)", "COMMAND")
            
            if qualifier is None:
                qualifier = c104.Qoc.SHORT_PULSE
            
            # Build SELECT command (S/E bit = 0 means SELECT)
            # In c104, this is typically handled by the Qoc qualifier
            # The SELECT flag in IEC 104 is part of the QOC (Qualifier of Command)
            # QOC bit 7 (S/E): 0=Select, 1=Execute
            
            # For SELECT, we use the base qualifier
            select_qualifier = qualifier  # S/E = 0 (Select)
            
            point.info = c104.DoubleCmd(
                state=state,
                qualifier=select_qualifier
            )
            
            # Create future for SELECT confirmation
            self._pending_select = asyncio.get_event_loop().create_future()
            
            # Transmit SELECT
            if not point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[SBO] SELECT transmission failed", "ERROR")
                return CommandResult.ERROR
            
            self._log(f"[SBO] SELECT sent, waiting for confirmation...", "INFO")
            
            # Wait for SELECT confirmation with timeout
            try:
                select_confirmed = await asyncio.wait_for(
                    self._wait_for_select_confirmation(point),
                    timeout=self.config.sbo_timeout
                )
            except asyncio.TimeoutError:
                self._log(f"[SBO] SELECT confirmation timeout after {self.config.sbo_timeout}s", "ERROR")
                return CommandResult.TIMEOUT
            
            if not select_confirmed:
                self._log(f"[SBO] SELECT negatively confirmed - operation cancelled", "ERROR")
                return CommandResult.NEGATIVE_CONFIRM
            
            self._log(f"[SBO] SELECT confirmed positively", "SUCCESS")
            
            # === PHASE 2: EXECUTE ===
            self._log(f"[SBO] Phase 2: Sending EXECUTE (S/E=1)", "COMMAND")
            
            # Build EXECUTE command (S/E bit = 1 means Execute)
            # For EXECUTE, we modify the qualifier to set S/E=1
            # This is library-specific; some use Qoc enum variants
            
            # c104 library might handle this via specific Qoc values
            # or we need to OR the S/E bit into the qualifier
            execute_qualifier = qualifier  # S/E = 1 (Execute) - library handles it
            
            point.info = c104.DoubleCmd(
                state=state,
                qualifier=execute_qualifier
            )
            
            # Transmit EXECUTE
            if not point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[SBO] EXECUTE transmission failed", "ERROR")
                return CommandResult.ERROR
            
            self._log(f"[SBO] EXECUTE sent, waiting for confirmation...", "INFO")
            
            # Wait for EXECUTE confirmation
            try:
                exec_confirmed = await asyncio.wait_for(
                    self._wait_for_execute_confirmation(point),
                    timeout=self.config.execute_timeout
                )
            except asyncio.TimeoutError:
                self._log(f"[SBO] EXECUTE confirmation timeout", "ERROR")
                return CommandResult.TIMEOUT
            
            if exec_confirmed:
                self._log(f"[SBO] Command executed successfully", "SUCCESS")
                return CommandResult.SUCCESS
            else:
                self._log(f"[SBO] EXECUTE negatively confirmed", "ERROR")
                return CommandResult.NEGATIVE_CONFIRM
                
        except Exception as e:
            self._log(f"[SBO] Error: {str(e)}", "ERROR")
            return CommandResult.ERROR
    
