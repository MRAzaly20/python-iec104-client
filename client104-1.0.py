    def _get_qoc_qualifier(self):
        """Map QOC qualifier dropdown value to c104.Qoc enum."""
        qoc_map = {
            "No Pulse": c104.Qoc.NONE,
            "Short Pulse": c104.Qoc.SHORT_PULSE,
            "Long Pulse": c104.Qoc.LONG_PULSE,
            "Persistent": c104.Qoc.PERSISTENT,
        }
        return qoc_map.get(self.qoc_qualifier_var.get(), c104.Qoc.LONG_PULSE)
    
    def _validate_cmd_prereqs(self, expected_types=None):
        """Common validation for all command send methods. Returns (conn, ioa, command_point) or None."""
        if self._dco_selected_ioa is None:
            self.log_message("No IOA selected! Select a command point first.", "ERROR")
            self.dco_cmd_status.configure(text="✗ No IOA selected", text_color=COLORS["error"])
            return None
        
        if expected_types and self._dco_selected_type not in expected_types:
            self.log_message(
                f"IOA {self._dco_selected_ioa} is type {self._dco_selected_type}, expected {expected_types}!", "ERROR")
            self.dco_cmd_status.configure(
                text=f"✗ Wrong type: {self._dco_selected_type}", text_color=COLORS["error"])
            return None
        
        if not self._is_connected():
            self.log_message("Cannot send command: not connected", "ERROR")
            self.dco_cmd_status.configure(text="✗ Not connected", text_color=COLORS["error"])
            return None
        
        conn = self.active_conn
        ioa = self._dco_selected_ioa
        type_name = self._dco_selected_type
        command_point = conn.monitoring_points.get((type_name, ioa))
        if command_point is None:
            self.log_message(f"Command point IOA {ioa} not registered!", "ERROR")
            self.dco_cmd_status.configure(text=f"✗ IOA {ioa} not registered", text_color=COLORS["error"])
            return None
        
        return conn, ioa, command_point
    
