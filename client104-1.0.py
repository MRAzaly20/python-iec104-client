    def _is_connected(self):
        """Check if active connection is connected."""
        conn = self.active_conn
        return conn.is_connected() if conn else False
    
    def _execute_async(self, coro):
        """Execute an async coroutine on the active connection's event loop."""
        conn = self.active_conn
        if conn and conn.loop and not conn.loop.is_closed():
            future = asyncio.run_coroutine_threadsafe(coro, conn.loop)
            future.add_done_callback(self.async_exception_handler)
        else:
            self.log_message("IEC 104 event loop not available", "ERROR")
    
    def _execute_in_thread(self, func, *args, **kwargs):
        """Execute a synchronous function in a daemon thread (non-blocking)."""
        thread = threading.Thread(target=func, args=args, kwargs=kwargs, daemon=True)
        thread.start()
    
