# Multi-Connection Config Helpers
# =============================================================================

def load_connections_config(filepath: str) -> list:
    """Load config file. Auto-detects old single-station vs new multi-connection format."""
    import json
    with open(filepath, 'r') as f:
        data = json.load(f)

    if isinstance(data, dict) and 'connections' in data:
        return [StationConfig.from_dict(c) for c in data['connections']]
    elif isinstance(data, dict):
        # Old single-station format — wrap it
        return [StationConfig.from_dict(data)]
    else:
        return []


def save_connections_config(filepath: str, connections: dict):
    """Save all connections to JSON in new multi-connection format."""
    import json
    payload = {
        'connections': [conn.config.to_dict() for conn in connections.values()]
    }
    with open(filepath, 'w') as f:
        json.dump(payload, f, indent=2)


