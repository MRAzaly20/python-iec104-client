    def _remove_selected_groups(self, rows):
        """Remove selected group rows."""
        # iterate backwards to safely remove
        removed = 0
        for i in range(len(rows) - 1, -1, -1):
            row = rows[i]
            if row['select'].get():
                row['frame'].destroy()
                rows.pop(i)
                removed += 1
        
        if removed == 0:
            messagebox.showinfo("Info", "No groups selected for deletion")
    
    def manual_connect(self):
        """Connect the active connection."""
        conn = self.active_conn
        if not conn:
            messagebox.showerror("Error", "No connection selected")
            return
        if conn.is_connected() or conn.running:
            self.log_message(f"[{conn.id}] Already connected or connecting", "INFO")
            return
        
        conn.start(self)
        self.update_connection_buttons(connected=False)  # Will update when actually connected
        self.log_message(f"Connecting {conn.id}...", "COMMAND")
    
    def manual_disconnect(self):
        """Disconnect the active connection."""
        conn = self.active_conn
        if not conn:
            return
        
        conn.stop()
        self.update_connection_status("DISCONNECTED")
        self.update_connection_buttons(connected=False)
        self._populate_groups_tree()
        self.log_message(f"[{conn.id}] Disconnected by user", "INFO")
    
    def toggle_auto_reconnect(self):
        """Toggle auto-reconnect setting."""
        enabled = self.auto_reconnect_var.get()
        conn = self.active_conn
        if conn:
            conn.auto_reconnect_enabled = enabled
        status = "enabled" if enabled else "disabled"
        self.log_message(f"Auto-reconnect {status}", "INFO")

    def toggle_auto_sync(self):
        """Toggle auto-sync setting."""
        enabled = self.auto_sync_var.get()
        self.time_sync_config.auto_sync_enabled = enabled
        conn = self.active_conn
        if conn and conn.time_sync_mgr:
            conn.time_sync_mgr.config.auto_sync_enabled = enabled
            if not enabled:
                conn.time_sync_mgr.stop()
        
        status = "enabled" if enabled else "disabled"
        self.log_message(f"Auto-sync {status}", "INFO")

    def manual_time_sync(self):
        """Send manual time sync command directly."""
        if not self._is_connected():
            self.log_message("Cannot sync time: not connected", "ERROR")
            return
        conn = self.active_conn
        if conn and conn.time_sync_mgr:
            self._execute_async(conn.time_sync_mgr.send_clock_sync())
            self.log_message("Sending Time Sync command...", "COMMAND")
        else:
            self.log_message("Time sync not available", "ERROR")
    
    def _auto_reconnect_after_config_change(self):
        """Automatically disconnect and reconnect the active connection after config change."""
        conn = self.active_conn
        if not conn:
            return
        
        was_connected = conn.is_connected() or conn.running
        
        if was_connected:
            self.log_message(f"[{conn.id}] Auto-reconnecting to register new points...", "INFO")
            conn.stop()
            self.root.after(500, self._reconnect_after_delay)
        else:
            self.log_message(f"[{conn.id}] Connecting to register new points...", "INFO")
            conn.start(self)
    
    def _reconnect_after_delay(self):
        """Reconnect active connection after a brief delay."""
        conn = self.active_conn
        if not conn:
            return
        self.update_connection_status("DISCONNECTED")
        self.update_connection_buttons(connected=False)
        conn.start(self)
        self.log_message(f"[{conn.id}] Reconnecting...", "COMMAND")
    
    def update_connection_buttons(self, connected: bool):
        """Update button states based on connection status."""
        if connected:
            self.btn_connect.configure(state="disabled")
            self.btn_disconnect.configure(state="normal")
        else:
            self.btn_connect.configure(state="normal")
            self.btn_disconnect.configure(state="disabled")
        
    def initialize_points_tree(self):
        """Initialize tree with point definitions from StationConfig."""
        # Clear existing items
        for item in self.tree.get_children():
            self.tree.delete(item)
        
        # Add all points with new column structure matching reference interface
        for group in self.station_config.groups:
            for point in group.points:
                item_id = f"point_{point.asdu_type.name}_{point.ioa}"
                # Columns: IOA, VariableName, DCS, QOC_QU, QOC_SE, DateTime, 
                #          Mapped_Point_CA, Mapped_Point_TypeID, Mapped_Point_IOA
                self.tree.insert('', 'end', iid=item_id,
                    values=(
                        point.ioa,                                      # IOA
                        point.name,                                      # VariableName
                        0,                                               # DCS (Double Command State)
                        0,                                               # QOC_QU (Qualifier)
                        'False',                                         # QOC_SE (Select/Execute)
                        datetime.now().strftime("%Y-%m-%d %H:%M:%S +07:00"),  # DateTime
                        self.station_config.common_address,              # Mapped Point CA
                        point.asdu_type.name,                            # TypeID
                        point.ioa                                        # Mapped IOA
                    ))
                self.points_data[point.ioa] = {
                    'type': point.asdu_type.name,
                    'description': point.name,
                    'value': 0,
                    'quality': 'UNKNOWN',
                    'timestamp': '-',
                    'count': 0,
                    'data_point': point
                }
        
        # Log summary
        total_points = len(self.station_config.get_all_points())
        self.log_message(f"Loaded {len(self.station_config.groups)} groups with {total_points} points", "INFO")

    
