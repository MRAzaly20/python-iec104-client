    def send_setpoint_command(self):
        """Send a Set-point Command (C_SE_NA_1 / NB_1 / NC_1 / TC_1) from the panel input."""
        prereq = self._validate_cmd_prereqs(("C_SE_NA_1", "C_SE_NB_1", "C_SE_NC_1", "C_SE_TC_1"))
        if not prereq:
            return
        conn, ioa, command_point = prereq
        
        raw_val = self.se_value_var.get().strip()
        point_type = self._dco_selected_type
        try:
            if point_type == "C_SE_NB_1":
                value = int(raw_val)
                if not (-32768 <= value <= 32767):
                    raise ValueError("Scaled value must be -32768..32767")
            elif point_type == "C_SE_NA_1":
                value = float(raw_val)
                if not (-1.0 <= value <= 1.0):
                    raise ValueError("Normalized value must be -1.0..1.0")
            else:
                value = float(raw_val)
        except ValueError as e:
            self.log_message(f"Invalid set-point value: {e}", "ERROR")
            self.dco_cmd_status.configure(text=f"✗ Invalid value: {e}", text_color=COLORS["error"])
            return
        
        self._execute_in_thread(self.send_command_async, command_point, str(value), "SE", None, point_type, value)
        self.log_message(
            f"Sending SE {point_type} value={value} to IOA {ioa}...", "COMMAND")
        self.dco_cmd_status.configure(text=f"⌛ {value} → IOA {ioa}...", text_color=COLORS["accent"])
    
