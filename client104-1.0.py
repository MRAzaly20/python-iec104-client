# ConnectionInstance — Encapsulates all per-connection state
# =============================================================================

class ConnectionInstance:
    """Encapsulates all state for a single IEC 104 server connection.
    
    Each instance owns its own c104.Client, Connection, Station,
    monitoring_points dict, asyncio event loop, and daemon thread.
    """

    def __init__(self, conn_id: str, config: StationConfig,
                 flow_config: 'IEC104FlowControlConfig' = None,
                 time_sync_config: 'IEC104TimeSyncConfig' = None):
        self.id = conn_id
        self.config = config

        # c104 objects — created in run_loop
        self.client: Optional[c104.Client] = None
        self.connection: Optional[c104.Connection] = None
        self.station: Optional[c104.Station] = None
        self.monitoring_points: dict = {}

        # Threading / async
        self.loop: Optional[asyncio.AbstractEventLoop] = None
        self._thread: Optional[threading.Thread] = None
        self.running = False
        self.stop_flag = False

        # Auto-reconnect
        self.auto_reconnect_enabled = True
        self.reconnect_interval = 5.0
        self.max_reconnect_attempts = 0
        self.reconnect_count = 0

        # Managers — created in run_loop
        self.flow_config = flow_config
        self.time_sync_config = time_sync_config
        self.flow_mgr: Optional['FlowControlManager'] = None
        self.time_sync_mgr: Optional['TimeSyncManager'] = None

    # ------------------------------------------------------------------
    def is_connected(self) -> bool:
        return (self.connection is not None
                and self.connection.state == c104.ConnectionState.OPEN
                and self.loop is not None)

    # ------------------------------------------------------------------
    def start(self, gui: 'IEC104ClientGUI'):
        """Launch run_loop in a daemon thread."""
        if self._thread and self._thread.is_alive():
            return  # already running
        self.stop_flag = False
        self.reconnect_count = 0
        self._thread = threading.Thread(
            target=self._run_in_thread, args=(gui,), daemon=True
        )
        self._thread.start()

    def _run_in_thread(self, gui: 'IEC104ClientGUI'):
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        self.loop = loop
        try:
            loop.run_until_complete(self.run_loop(gui))
        finally:
            self.loop = None
            loop.close()

    # ------------------------------------------------------------------
    def stop(self):
        """Signal the loop to stop and clean up."""
        self.stop_flag = True
        self.running = False

        if self.flow_mgr:
            self.flow_mgr.stop()
        if self.time_sync_mgr:
            self.time_sync_mgr.stop()

        client = self.client
        if client:
            try:
                client.stop()
            except Exception:
                pass

    # ------------------------------------------------------------------
    def execute_async(self, coro):
        """Schedule an async coroutine on this connection's event loop."""
        if self.loop and not self.loop.is_closed():
            future = asyncio.run_coroutine_threadsafe(coro, self.loop)
            return future
        return None

    def execute_in_thread(self, func, *args, **kwargs):
        """Run a synchronous function in a new daemon thread."""
        t = threading.Thread(target=func, args=args, kwargs=kwargs, daemon=True)
        t.start()

    # ------------------------------------------------------------------
    async def run_loop(self, gui: 'IEC104ClientGUI'):
        """Main IEC 104 client logic with auto-reconnection (per-connection)."""
        loop = asyncio.get_event_loop()
        self.running = True
        fc = self.flow_config or IEC104FlowControlConfig()
        tsc = self.time_sync_config or IEC104TimeSyncConfig()

        while self.running and not self.stop_flag:
            connection_timeout_flag = [False]

            def send_testfr_callback() -> bool:
                try:
                    if self.connection and self.connection.state == c104.ConnectionState.OPEN:
                        gui.root.after(0, gui.log_message,
                                       f"[{self.id}][TESTFR] Sending TESTFR_ACT", "COMMAND")
                        return True
                    return False
                except Exception as e:
                    gui.root.after(0, gui.log_message,
                                   f"[{self.id}][TESTFR] Error: {e}", "ERROR")
                    return False

            def connection_timeout_callback():
                connection_timeout_flag[0] = True
                gui.root.after(0, gui.log_message,
                               f"[{self.id}][FlowControl] Timeout – closing", "ERROR")
                gui.root.after(0, gui._update_conn_sidebar_status, self.id, "TIMEOUT")

            try:
                self.client = c104.Client()
                self.connection = self.client.add_connection(
                    ip=self.config.server_ip,
                    port=self.config.server_port,
                    init=c104.Init.ALL
                )
                self.station = self.connection.add_station(
                    common_address=self.config.common_address
                )

                self.flow_mgr = FlowControlManager(
                    config=fc,
                    on_send_testfr=send_testfr_callback,
                    on_connection_timeout=connection_timeout_callback,
                    on_log=gui.log_message
                )

                gui.root.after(0, gui.log_message,
                    f"[{self.id}] Connecting to {self.config.server_ip}:{self.config.server_port}...",
                    "COMMAND")
                gui.root.after(0, gui._update_conn_sidebar_status, self.id, "CONNECTING")

                self.monitoring_points = {}
                for group in self.config.groups:
                    for dp in group.points:
                        try:
                            c104_type = dp.asdu_type.to_c104_type()
                            if c104_type is None:
                                continue
                            point = self.station.add_point(
                                io_address=dp.ioa, type=c104_type
                            )
                            if dp.asdu_type.name.startswith('M_'):
                                point.on_receive(
                                    callable=functools.partial(
                                        gui.on_receive_point, loop=loop
                                    )
                                )
                            self.monitoring_points[(dp.asdu_type.name, dp.ioa)] = point
                            dp.c104_point = point
                        except Exception as e:
                            gui.root.after(0, gui.log_message,
                                f"[{self.id}] Error registering IOA {dp.ioa}: {e}", "ERROR")

                gui.root.after(0, gui.log_message,
                    f"[{self.id}] Registered {len(self.monitoring_points)} points", "SUCCESS")

                self.client.start()

                # Wait for connection
                t0 = time.monotonic()
                while self.connection.state != c104.ConnectionState.OPEN:
                    if self.stop_flag or not self.running:
                        break
                    if time.monotonic() - t0 > 30.0:
                        raise ConnectionError("Connection timeout")
                    await asyncio.sleep(0.5)

                if self.stop_flag or not self.running:
                    break

                self.reconnect_count = 0
                gui.root.after(0, gui._update_conn_sidebar_status, self.id, "CONNECTED")
                gui.root.after(0, gui.log_message,
                    f"[{self.id}] Connected to {self.config.server_ip}:{self.config.server_port}",
                    "SUCCESS")

                # Update buttons if this is the active connection
                gui.root.after(0, gui._maybe_update_buttons_for, self.id, True)

                self.flow_mgr.start(loop)

                self.time_sync_mgr = TimeSyncManager(
                    config=tsc, station=self.station,
                    on_log=lambda msg, lvl: gui.root.after(0, gui.log_message, msg, lvl)
                )
                self.time_sync_mgr.start_auto_sync(loop)

                # Monitor connection
                while (self.connection.state == c104.ConnectionState.OPEN
                       and not connection_timeout_flag[0]
                       and self.running and not self.stop_flag):
                    await asyncio.sleep(0.1)

                if self.flow_mgr:
                    self.flow_mgr.stop()
                    self.flow_mgr = None
                if self.time_sync_mgr:
                    self.time_sync_mgr.stop()
                    self.time_sync_mgr = None

                if self.stop_flag:
                    gui.root.after(0, gui._update_conn_sidebar_status, self.id, "DISCONNECTED")
                    gui.root.after(0, gui.log_message,
                        f"[{self.id}] Disconnected by user", "INFO")
                    break
                elif connection_timeout_flag[0]:
                    gui.root.after(0, gui._update_conn_sidebar_status, self.id, "TIMEOUT")
                else:
                    gui.root.after(0, gui._update_conn_sidebar_status, self.id, "DISCONNECTED")
                    gui.root.after(0, gui.log_message,
                        f"[{self.id}] Connection lost", "ERROR")

            except Exception as e:
                if self.flow_mgr:
                    self.flow_mgr.stop()
                    self.flow_mgr = None
                gui.root.after(0, gui.log_message,
                    f"[{self.id}] Error: {e}", "ERROR")
                gui.root.after(0, gui._update_conn_sidebar_status, self.id, "ERROR")

            finally:
                if self.client:
                    try:
                        self.client.stop()
                    except Exception:
                        pass
                    self.client = None
                self.connection = None
                self.station = None

            # Auto-reconnect
            if (self.auto_reconnect_enabled and self.running and not self.stop_flag):
                self.reconnect_count += 1
                if (self.max_reconnect_attempts > 0
                        and self.reconnect_count >= self.max_reconnect_attempts):
                    gui.root.after(0, gui.log_message,
                        f"[{self.id}] Max reconnect attempts reached", "ERROR")
                    break

                gui.root.after(0, gui._update_conn_sidebar_status, self.id, "RECONNECTING")
                gui.root.after(0, gui.log_message,
                    f"[{self.id}] Reconnect #{self.reconnect_count} in {self.reconnect_interval}s...",
                    "RECONNECT")

                for _ in range(int(self.reconnect_interval * 10)):
                    if self.stop_flag or not self.running:
                        break
                    await asyncio.sleep(0.1)
            else:
                break

        self.running = False
        gui.root.after(0, gui._maybe_update_buttons_for, self.id, False)


