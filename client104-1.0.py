    def write_double_command_dialog(self, ioa):
        """Dialog for writing double command value"""
        result = messagebox.askyesno("Write Double Command", f"Write value to IOA {ioa}?\n\nYES = True\nNO = False")
        if result is not None:
            value = "ON" if result else "OFF"
            
            conn = self.active_conn
            if not conn:
                self.log_message("No active connection", "ERROR")
                return
            
            # Check if point is registered — get type from config
            pt = self.station_config.get_point_by_ioa(ioa)
            pt_type = pt.asdu_type.name if pt else None
            command_point = conn.monitoring_points.get((pt_type, ioa)) if pt_type else None
            if command_point is None:
                # Point not registered yet - show error with helpful message
                self.log_message(f"IOA {ioa} not registered with server. Please reconnect first.", "ERROR")
                messagebox.showerror("Command Error", 
                    f"IOA {ioa} is not registered with the IEC 104 server.\n\n"
                    "Points are only registered when connected to the server.\n\n"
                    "Please:\n"
                    "1. Click 'Reload Config' to update configuration\n"
                    "2. Click 'Disconnect' then 'Connect' to re-register points")
