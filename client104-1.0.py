@dataclass
class IEC104FlowControlConfig:
    """
    IEC 60870-5-104 Flow Control Parameters.
    
    k: Maximum number of outstanding I-Frames (unacknowledged APDUs).
       Default: 12 (Standard range: 1-32767)
    w: Latest Acknowledged I-Frame threshold. Triggers S-Frame when reached.
       Default: 8 (Standard: w <= 2/3 * k)
    t1: Timeout for acknowledgment of APDU (seconds).
        Default: 15s (Standard range: 1-255s)
    t2: Timeout for acknowledgment by S-Frame if no I-Frame available (seconds).
        Default: 10s (Standard range: 1-255s, t2 < t1)
    t3: Timeout for sending TESTFR if no traffic (seconds).
        Default: 20s (Standard range: 1-172800s)
    """
    k: int = 12          # Max outstanding I-Frames
    w: int = 8           # Acknowledgment threshold
    t1: float = 15.0     # ACK timeout (seconds)
    t2: float = 10.0     # S-Frame timeout (seconds)
    t3: float = 20.0     # TESTFR timeout (seconds)
    
    def __post_init__(self):
        """Validate parameters according to IEC 104 standard."""
        if not (1 <= self.k <= 32767):
            raise ValueError(f"k must be in range [1, 32767], got {self.k}")
        if not (1 <= self.w <= 32767):
            raise ValueError(f"w must be in range [1, 32767], got {self.w}")
        if self.w > self.k:
            raise ValueError(f"w ({self.w}) must be <= k ({self.k})")
        if not (1 <= self.t1 <= 255):
            raise ValueError(f"t1 must be in range [1, 255], got {self.t1}")
        if not (1 <= self.t2 <= 255):
            raise ValueError(f"t2 must be in range [1, 255], got {self.t2}")
        if self.t2 >= self.t1:
            raise ValueError(f"t2 ({self.t2}) must be < t1 ({self.t1})")
        if not (1 <= self.t3 <= 172800):
            raise ValueError(f"t3 must be in range [1, 172800], got {self.t3}")


class TestFrameState(Enum):
    """State of TESTFR exchange."""
    IDLE = auto()
    WAITING_CON = auto()  # Sent TESTFR_ACT, waiting for TESTFR_CON


class FlowControlManager:
    """
    Manages IEC 104 Flow Control timers and TESTFR keep-alive mechanism.
    
    Timer Logic:
    - t3: If no APDU received for t3 seconds, send TESTFR_ACT.
    - t1: If TESTFR_CON not received within t1 after TESTFR_ACT, close connection.
    """
    
    def __init__(
        self, 
        config: IEC104FlowControlConfig,
        on_send_testfr: Callable[[], bool],
        on_connection_timeout: Callable[[], None],
        on_log: Optional[Callable[[str, str], None]] = None
    ):
        """
        Initialize FlowControlManager.
        
        Args:
            config: IEC 104 flow control parameters.
            on_send_testfr: Callback to send TESTFR_ACT. Returns True if sent.
            on_connection_timeout: Callback when t1 timeout occurs (close connection).
            on_log: Optional logging callback (message, level).
        """
        self.config = config
        self._on_send_testfr = on_send_testfr
        self._on_connection_timeout = on_connection_timeout
        self._on_log = on_log or (lambda msg, lvl: None)
        
        # State tracking
        self._last_apdu_received_time: float = time.monotonic()
        self._testfr_state: TestFrameState = TestFrameState.IDLE
        self._testfr_sent_time: Optional[float] = None
        
        # Sequence numbers (for future expansion)
        self._send_sequence_number: int = 0  # N(S)
        self._receive_sequence_number: int = 0  # N(R)
        self._unacked_i_frames: int = 0
        
        # Control flags
        self._running: bool = False
        self._timer_task: Optional[asyncio.Task] = None
    
    def start(self, loop: asyncio.AbstractEventLoop) -> None:
        """Start the flow control timer loop."""
        self._running = True
        self._last_apdu_received_time = time.monotonic()
        self._on_log("[FlowControl] Timer started", "INFO")
    
    def stop(self) -> None:
        """Stop the flow control timer loop."""
        self._running = False
        if self._timer_task:
            self._timer_task.cancel()
            self._timer_task = None
        self._on_log("[FlowControl] Timer stopped", "INFO")
    
    def on_apdu_received(self) -> None:
        """
        Called when ANY APDU is received from the server.
        Resets the t3 timer.
        """
        self._last_apdu_received_time = time.monotonic()
        
        # If we were waiting for TESTFR_CON and received ANY packet, 
        # the connection is alive
        if self._testfr_state == TestFrameState.WAITING_CON:
            self._on_log("[FlowControl] TESTFR_CON received (or traffic detected)", "SUCCESS")
            self._testfr_state = TestFrameState.IDLE
            self._testfr_sent_time = None
    
    def on_testfr_con_received(self) -> None:
        """Called specifically when TESTFR_CON is received."""
        self._last_apdu_received_time = time.monotonic()
        if self._testfr_state == TestFrameState.WAITING_CON:
            self._on_log("[FlowControl] TESTFR_CON confirmed", "SUCCESS")
            self._testfr_state = TestFrameState.IDLE
            self._testfr_sent_time = None
    
    async def _timer_loop(self) -> None:
        """Main timer loop for t3 and t1 timeout handling."""
        while self._running:
            try:
                await asyncio.sleep(1.0)  # Check every second
                
                current_time = time.monotonic()
                elapsed_since_last_apdu = current_time - self._last_apdu_received_time
                
                if self._testfr_state == TestFrameState.IDLE:
                    # Check t3: No APDU received for t3 seconds
                    if elapsed_since_last_apdu >= self.config.t3:
                        self._on_log(
                            f"[FlowControl] t3 timeout ({self.config.t3}s) - Sending TESTFR_ACT",
                            "COMMAND"
                        )
                        if self._on_send_testfr():
                            self._testfr_state = TestFrameState.WAITING_CON
                            self._testfr_sent_time = current_time
                        else:
                            self._on_log("[FlowControl] Failed to send TESTFR_ACT", "ERROR")
                
                elif self._testfr_state == TestFrameState.WAITING_CON:
                    # Check t1: Waiting for TESTFR_CON
                    if self._testfr_sent_time:
                        elapsed_since_testfr = current_time - self._testfr_sent_time
                        if elapsed_since_testfr >= self.config.t1:
                            self._on_log(
                                f"[FlowControl] t1 timeout ({self.config.t1}s) - "
                                "TESTFR_CON not received, closing connection",
                                "ERROR"
                            )
                            self._on_connection_timeout()
                            self._running = False
                            break
                            
            except asyncio.CancelledError:
                break
            except Exception as e:
                self._on_log(f"[FlowControl] Timer error: {e}", "ERROR")
    
    @property
    def is_connection_healthy(self) -> bool:
        """Check if connection is considered healthy."""
        return self._testfr_state == TestFrameState.IDLE


