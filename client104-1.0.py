    def on_group_selected(self, event):
        """Handle group selection in sidebar."""
        selection = self.groups_tree.selection()
        if selection:
            item = selection[0]
            tags = self.groups_tree.item(item, 'tags')
            if 'connection' in tags:
                # Clicked a connection root → switch active connection
                cid = tags[1] if len(tags) > 1 else None
                if cid and cid in self.connections:
                    self.active_conn_id = cid
                    self._on_active_connection_changed()
                    self._show_all_points()
            elif 'group' in tags:
                group_name = tags[1] if len(tags) > 1 else None
                # If the tag also has a connection id, switch to it
                cid = tags[2] if len(tags) > 2 else None
                if cid and cid in self.connections:
                    self.active_conn_id = cid
                    self._on_active_connection_changed()
                if group_name:
                    self._filter_points_by_group(group_name)
            else:
                self._show_all_points()
    
