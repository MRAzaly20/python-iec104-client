class CP56Time2a:
    """
    Helper class for IEC 60870-5-104 CP56Time2a timestamp format.
    Format (7 octets):
    - Octet 1-2: Milliseconds (0-59999)
    - Octet 3: Minutes (0-59), IV (Invalid) flag (bit 7)
    - Octet 4: Hours (0-23), SU (Summer Time) flag (bit 7)
    - Octet 5: Day of Month (1-31), Day of Week (1-7) in bits 5-7
    - Octet 6: Month (1-12)
    - Octet 7: Year (0-99)
    """
    
    @staticmethod
    def encode(dt: datetime, iv: bool = False, su: bool = False) -> bytes:
        """Encode datetime to CP56Time2a 7-byte format."""
        # Calculate milliseconds
        ms = dt.microsecond // 1000 + dt.second * 1000
        
        # Octet 1-2: Milliseconds
        octet1 = ms & 0xFF
        octet2 = (ms >> 8) & 0xFF
        
        # Octet 3: Minutes + IV flag (bit 7) + RES (bit 6 is 0)
        octet3 = dt.minute & 0x3F
        if iv:
            octet3 |= 0x80
            
        # Octet 4: Hours + SU flag (bit 7) + RES (bit 6 is 0)
        octet4 = dt.hour & 0x1F
        if su:
            octet4 |= 0x80
            
        # Octet 5: Day of Month + Day of Week
        # DoW: 1=Mon, ..., 7=Sun. Python isoweekday() matches this.
        dow = dt.isoweekday()
        octet5 = (dt.day & 0x1F) | ((dow & 0x07) << 5)
        
        # Octet 6: Month (bits 0-3), bits 4-7 RES (0)
        octet6 = dt.month & 0x0F
        
        # Octet 7: Year (0-99)
        year = dt.year % 100
        octet7 = year & 0x7F
        
        return bytes([octet1, octet2, octet3, octet4, octet5, octet6, octet7])
    
    @staticmethod
    def decode(data: bytes) -> datetime:
        """Decode CP56Time2a 7-byte format to datetime."""
        if len(data) != 7:
            raise ValueError(f"Invalid CP56Time2a length: {len(data)}")
            
        # Octet 1-2: Milliseconds
        ms = data[0] | (data[1] << 8)
        seconds = ms // 1000
        microseconds = (ms % 1000) * 1000
        
        # Octet 3: Minutes (mask 0x3F)
        minutes = data[2] & 0x3F
        iv = bool(data[2] & 0x80)
        
        # Octet 4: Hours (mask 0x1F)
        hours = data[3] & 0x1F
        su = bool(data[3] & 0x80)
        
        # Octet 5: Day (mask 0x1F)
        day = data[4] & 0x1F
        
        # Octet 6: Month (mask 0x0F)
        month = data[5] & 0x0F
        
        # Octet 7: Year
        year = 2000 + (data[6] & 0x7F)  # Assume 20xx
        
        return datetime(year, month, day, hours, minutes, seconds, microseconds)

    @staticmethod
    def get_flags(data: bytes) -> tuple[bool, bool]:
        """Extract (IV, SU) flags from CP56Time2a bytes."""
        if len(data) != 7:
            return False, False
        iv = bool(data[2] & 0x80)
        su = bool(data[3] & 0x80)
        return iv, su


