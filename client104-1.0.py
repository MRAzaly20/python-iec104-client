# IEC 104 Set Point Command (C_SE_NC_1 - TypeID 50) Short Floating Point
# =============================================================================
@dataclass
class QOS:
    """
    Qualifier of Set-point command (QOS) - 1 byte.
    
    Bit structure:
    - Bits 0-6: QL (Qualifier Level, 0 = default)
    - Bit 7: S/E (Select/Execute flag)
        - 0 = Execute
        - 1 = Select
    """
    select: bool = False  # S/E bit: True=Select, False=Execute
    ql: int = 0           # Qualifier level (0-127)
    
    def encode(self) -> int:
        """Encode QOS to a single byte."""
        qos_byte = self.ql & 0x7F  # Bits 0-6
        if self.select:
            qos_byte |= 0x80       # Bit 7 = 1 for Select
        return qos_byte
    
    @staticmethod
    def decode(byte_val: int) -> 'QOS':
        """Decode QOS from a single byte."""
        return QOS(
            select=bool(byte_val & 0x80),
            ql=byte_val & 0x7F
        )


class SetPointCommandASDU:
    """
    ASDU structure for C_SE_NC_1 (Set-point command, short floating point).
    TypeID: 50
    
    Structure (8 bytes for information object):
    ┌─────────────────────────────────────────────────────────────────┐
    │  IOA (3 bytes)  │  Value (4 bytes, IEEE 754)  │  QOS (1 byte)   │
    └─────────────────────────────────────────────────────────────────┘
    
    IOA: Information Object Address (24-bit, little-endian)
    Value: IEEE 754 single-precision floating point (32-bit, little-endian)
    QOS: Qualifier of Set-point (8-bit)
        - Bits 0-6: QL (qualifier level)
        - Bit 7: S/E (0=Execute, 1=Select)
    """
    TYPE_ID = 50  # C_SE_NC_1
    
    @staticmethod
    def encode_value(value: float) -> bytes:
        """Encode float value to IEEE 754 (4 bytes, little-endian)."""
        return struct.pack('<f', value)
    
    @staticmethod
    def decode_value(data: bytes) -> float:
        """Decode IEEE 754 bytes to float."""
        if len(data) != 4:
            raise ValueError(f"Invalid IEEE 754 length: {len(data)}")
        return struct.unpack('<f', data)[0]
    
    @staticmethod
    def encode_ioa(ioa: int) -> bytes:
        """Encode IOA to 3 bytes (little-endian)."""
        return struct.pack('<I', ioa)[:3]  # Take lower 3 bytes
    
    @staticmethod
    def decode_ioa(data: bytes) -> int:
        """Decode 3-byte IOA."""
        if len(data) != 3:
            raise ValueError(f"Invalid IOA length: {len(data)}")
        return struct.unpack('<I', data + b'\x00')[0]
    
    @staticmethod
    def build_information_object(ioa: int, value: float, qos: QOS) -> bytes:
        """
        Build complete information object for C_SE_NC_1.
        
        Args:
            ioa: Information Object Address (0-16777215)
            value: Setpoint value as IEEE 754 float
            qos: Qualifier of Set-point
            
        Returns:
            8 bytes: IOA (3) + Value (4) + QOS (1)
        """
        ioa_bytes = SetPointCommandASDU.encode_ioa(ioa)
        value_bytes = SetPointCommandASDU.encode_value(value)
        qos_byte = bytes([qos.encode()])
        
        return ioa_bytes + value_bytes + qos_byte
    
    @staticmethod
    def parse_information_object(data: bytes) -> tuple[int, float, QOS]:
        """Parse information object from bytes."""
        if len(data) != 8:
            raise ValueError(f"Invalid C_SE_NC_1 data length: {len(data)}")
            
        ioa = SetPointCommandASDU.decode_ioa(data[0:3])
        value = SetPointCommandASDU.decode_value(data[3:7])
        qos = QOS.decode(data[7])
        
        return ioa, value, qos


class SetPointSender:
    """
    Sends Set-point commands (C_SE_NC_1) with Select-Before-Operate support.
    
    Usage:
        sender = SetPointSender(config, station, on_log)
        result = await sender.send_setpoint_value(45.5, ioa=100, use_sbo=True)
    """
    
    def __init__(self, config: CommandSenderConfig,
                 station: c104.Station,
                 on_log: Optional[Callable[[str, str], None]] = None):
        self.config = config
        self.station = station
        self.on_log = on_log
        
    def _log(self, msg: str, level: str = "INFO"):
        """Log message if callback available."""
        if self.on_log:
            self.on_log(msg, level)
            
    async def send_setpoint_value(self, value: float, ioa: int, 
                                   use_sbo: bool = True) -> CommandResult:
        """
        Send a set-point command using Short Floating Point (C_SE_NC_1).
        
        Args:
            value: The floating-point setpoint value (IEEE 754)
            ioa: Information Object Address
            use_sbo: If True, use Select-Before-Operate; else Direct Execute
            
        Returns:
            CommandResult indicating success or failure
            
        Pseudocode:
            function sendSetpointValue(value, ioa, useSBO):
                if useSBO:
                    # Phase 1: SELECT
                    qos = QOS(select=True, ql=0)
                    asdu = buildASDU(ioa, value, qos)
                    send(asdu, COT=ACTIVATION)
                    
                    confirmation = waitForConfirmation()
                    if confirmation != POSITIVE:
                        return FAILURE
                    
                    # Phase 2: EXECUTE
                    qos = QOS(select=False, ql=0)
                    asdu = buildASDU(ioa, value, qos)
                    send(asdu, COT=ACTIVATION)
                    return waitForConfirmation()
                else:
                    # Direct Execute
                    qos = QOS(select=False, ql=0)
                    asdu = buildASDU(ioa, value, qos)
                    send(asdu, COT=ACTIVATION)
                    return waitForConfirmation()
        """
        try:
            self._log(f"[Setpoint] Sending value {value} to IOA {ioa} "
                     f"(SBO: {use_sbo})", "COMMAND")
            
            # Get or create setpoint point
            point = self._get_or_create_point(ioa)
            if point is None:
                self._log(f"[Setpoint] Failed to create point for IOA {ioa}", "ERROR")
                return CommandResult.ERROR
            
            if use_sbo:
                return await self._send_with_sbo(point, value, ioa)
            else:
                return await self._send_direct(point, value, ioa)
                
        except Exception as e:
            self._log(f"[Setpoint] Error: {str(e)}", "ERROR")
            return CommandResult.ERROR
            
    def _get_or_create_point(self, ioa: int) -> Optional[c104.Point]:
        """Get existing point or create new one for setpoint command."""
        try:
            # Try to find existing point
            point = None
            for p in self.station.points:
                if p.io_address == ioa:
                    point = p
                    break
                    
            # Create if not exists
            if point is None:
                point = self.station.add_point(
                    io_address=ioa,
                    type=c104.Type.C_SE_NC_1  # TypeID 50
                )
                
            return point
        except Exception as e:
            self._log(f"[Setpoint] Error getting/creating point: {e}", "ERROR")
            return None
    
    async def _send_direct(self, point: c104.Point, value: float, 
                           ioa: int) -> CommandResult:
        """Send setpoint using Direct Execute mode."""
        self._log(f"[Setpoint] Direct Execute: IOA {ioa} = {value}", "COMMAND")
        
        # Build QOS for Execute (S/E = 0)
        qos = QOS(select=False, ql=0)
        
        # Log ASDU structure for audit
        asdu_bytes = SetPointCommandASDU.build_information_object(ioa, value, qos)
        self._log(f"[Setpoint] ASDU: IOA={ioa}, Value={value:.6f} "
                 f"(0x{SetPointCommandASDU.encode_value(value).hex()}), "
                 f"QOS=0x{qos.encode():02X}", "INFO")
        
        # Set point info using c104 library
        try:
            # c104 library typically uses SetpointFloatCmd or similar
            if hasattr(c104, 'SetpointShortCmd'):
                point.info = c104.SetpointShortCmd(
                    value=value,
                    qualifier=qos.ql
                )
            elif hasattr(c104, 'MeasuredValueShortInfo'):
                # Fallback: use measurement info structure
                point.value = value
            else:
                # Generic approach
                point.info = type('SetpointInfo', (), {
                    'value': value,
                    'qos': qos.encode()
                })()
                
            # Transmit
            if point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[Setpoint] Command sent successfully", "SUCCESS")
                return CommandResult.SUCCESS
            else:
                self._log(f"[Setpoint] Transmission failed", "ERROR")
                return CommandResult.ERROR
                
        except Exception as e:
            self._log(f"[Setpoint] Direct execute error: {e}", "ERROR")
            return CommandResult.ERROR
    
    async def _send_with_sbo(self, point: c104.Point, value: float,
                              ioa: int) -> CommandResult:
        """Send setpoint using Select-Before-Operate mode."""
        
        # === PHASE 1: SELECT ===
        self._log(f"[Setpoint SBO] Phase 1: SELECT IOA {ioa}", "COMMAND")
        
        # Build QOS for Select (S/E = 1)
        qos_select = QOS(select=True, ql=0)
        
        # Log ASDU
        asdu_bytes = SetPointCommandASDU.build_information_object(ioa, value, qos_select)
        self._log(f"[Setpoint SBO] SELECT ASDU: 0x{asdu_bytes.hex()}", "INFO")
        
        try:
            if hasattr(c104, 'SetpointShortCmd'):
                point.info = c104.SetpointShortCmd(
                    value=value,
                    qualifier=qos_select.encode()
                )
            else:
                point.value = value
                
            if not point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[Setpoint SBO] SELECT transmission failed", "ERROR")
                return CommandResult.ERROR
                
        except Exception as e:
            self._log(f"[Setpoint SBO] SELECT error: {e}", "ERROR")
            return CommandResult.ERROR
        
        # Wait for SELECT confirmation
        self._log(f"[Setpoint SBO] Waiting for SELECT confirmation...", "INFO")
        
        try:
            confirmed = await asyncio.wait_for(
                self._wait_for_confirmation(point),
                timeout=self.config.sbo_timeout
            )
        except asyncio.TimeoutError:
            self._log(f"[Setpoint SBO] SELECT timeout", "ERROR")
            return CommandResult.TIMEOUT
        
        if not confirmed:
            self._log(f"[Setpoint SBO] SELECT negatively confirmed", "ERROR")
            return CommandResult.NEGATIVE_CONFIRM
            
        self._log(f"[Setpoint SBO] SELECT confirmed", "SUCCESS")
        
        # === PHASE 2: EXECUTE ===
        self._log(f"[Setpoint SBO] Phase 2: EXECUTE IOA {ioa}", "COMMAND")
        
        # Build QOS for Execute (S/E = 0)
        qos_execute = QOS(select=False, ql=0)
        
        asdu_bytes = SetPointCommandASDU.build_information_object(ioa, value, qos_execute)
        self._log(f"[Setpoint SBO] EXECUTE ASDU: 0x{asdu_bytes.hex()}", "INFO")
        
        try:
            if hasattr(c104, 'SetpointShortCmd'):
                point.info = c104.SetpointShortCmd(
                    value=value,
                    qualifier=qos_execute.encode()
                )
            else:
                point.value = value
                
            if not point.transmit(cause=c104.Cot.ACTIVATION):
                self._log(f"[Setpoint SBO] EXECUTE transmission failed", "ERROR")
                return CommandResult.ERROR
                
        except Exception as e:
            self._log(f"[Setpoint SBO] EXECUTE error: {e}", "ERROR")
            return CommandResult.ERROR
        
        # Wait for EXECUTE confirmation
        try:
            confirmed = await asyncio.wait_for(
                self._wait_for_confirmation(point),
                timeout=self.config.execute_timeout
            )
        except asyncio.TimeoutError:
            self._log(f"[Setpoint SBO] EXECUTE timeout", "ERROR")
            return CommandResult.TIMEOUT
        
        if confirmed:
            self._log(f"[Setpoint SBO] Setpoint executed successfully", "SUCCESS")
            return CommandResult.SUCCESS
        else:
            self._log(f"[Setpoint SBO] EXECUTE negatively confirmed", "ERROR")
            return CommandResult.NEGATIVE_CONFIRM
    
    async def _wait_for_confirmation(self, point: c104.Point) -> bool:
        """Wait for command confirmation from server."""
        max_polls = int(self.config.sbo_timeout * 10)
        for _ in range(max_polls):
            await asyncio.sleep(0.1)
            
            if hasattr(point, 'last_response') and point.last_response is not None:
                return point.last_response == c104.ResponseState.SUCCESS
                
        return False


