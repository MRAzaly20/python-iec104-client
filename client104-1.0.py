    def reload_config(self):
        """Reload all connections from config file."""
        try:
            config_file = Path(__file__).parent / "station_config.json"
            if not config_file.exists():
                self.log_message(f"Config file not found: {config_file.resolve()}", "ERROR")
                messagebox.showerror("Reload Failed", f"Config file not found:\n{config_file.resolve()}")
                return
            
            self.log_message(f"Reloading config from: {config_file.resolve()}", "INFO")
            
            # Stop all existing connections
            for conn in self.connections.values():
                conn.stop()
            
            # Reload
            configs = load_connections_config(str(config_file))
            self.connections = {}
            for sc in configs:
                cid = self._unique_conn_id(sc.name)
                self.connections[cid] = ConnectionInstance(
                    conn_id=cid, config=sc,
                    flow_config=self.flow_config,
                    time_sync_config=self.time_sync_config
                )
            
            if self.connections:
                self.active_conn_id = next(iter(self.connections))
            else:
                self.active_conn_id = None
            
            self._populate_groups_tree()
            self._on_active_connection_changed()
            self.initialize_points_tree()
            
            total = sum(len(c.config.get_all_points()) for c in self.connections.values())
            self.log_message(
                f"Reloaded: {len(self.connections)} connections, {total} total points", "SUCCESS")
            
            messagebox.showinfo("Config Reloaded", 
                f"Loaded {len(self.connections)} connection(s), {total} total points")
            
        except Exception as e:
            self.log_message(f"Failed to reload config: {e}", "ERROR")
            messagebox.showerror("Reload Failed", f"Error loading configuration:\n{str(e)}")

