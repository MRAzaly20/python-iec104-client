    def _remove_selected_groups(self, rows):
        """Remove selected group rows."""
        # iterate backwards to safely remove
        removed = 0
        for i in range(len(rows) - 1, -1, -1):
            row = rows[i]
            if row['select'].get():
                row['frame'].destroy()
                rows.pop(i)
                removed += 1
        
        if removed == 0:
            messagebox.showinfo("Info", "No groups selected for deletion")
    
    def manual_connect(self):
        """Handle manual connect button click."""
        # Use current configuration
        if not self.server_ip:
            messagebox.showerror("Error", "Server IP is required")
            return
        
        # Reset reconnect state
        self._stop_reconnect = False
        self.reconnect_attempt_count = 0
        
        # Disable connect button, enable disconnect
        self.connect_button.configure(state="disabled")
        
        # Start/restart client thread
        self.start_iec104_client()
        self.log_message(f"Connecting to {self.server_ip}:{self.server_port}...", "COMMAND")
    
    def manual_disconnect(self):
        """Handle manual disconnect button click."""
        self._stop_reconnect = True  # Prevent auto-reconnect
        self._client_running = False
        
        # Stop flow control manager
        if self.flow_control_manager:
            self.flow_control_manager.stop()
            # We don't set to None here to avoid race conditions with the thread
            
        # Stop time sync manager
        if self.time_sync_manager:
            self.time_sync_manager.stop()
        
        # Signal client to stop if it exists
        # We use a local reference to avoid race conditions
        client = self.client
        if client:
            try:
                # Use call_soon_threadsafe if we had the loop, but client.stop() is usually thread-safe enough
                # or just let the main loop exiting handle it. 
                # Calling stop() here helps break out of blocking calls if any.
                client.stop()
            except Exception:
                pass
        
        # Update UI immediately
        self.update_connection_status("DISCONNECTED")
        self.update_connection_buttons(connected=False)
        self.log_message("Disconnected by user", "INFO")
    
