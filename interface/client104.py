    def log_message(self, message, level="INFO"):
        """Add message to log - outputs to both GUI and console."""
        timestamp = datetime.now().strftime("%H:%M:%S")
        formatted_message = f"[{timestamp}] {message}\n"
        
        # Console logging
        level_prefix = {
            "INFO": "[INFO]",
            "ERROR": "[ERROR]",
            "SUCCESS": "[OK]",
            "COMMAND": "[CMD]",
            "WRITE": "[WRITE]",
            "DEBUG": "[DEBUG]"
        }.get(level, f"[{level}]")
        print(f"{level_prefix} {formatted_message.strip()}")
        
        # --- ENHANCED TRAFFIC MONITOR INTEGRATION ---
        # Parse basic messages into structured traffic data
        # determine category/direction based on level or message content
        
        category = "INFO"
        direction = "--"
        type_name = level
        ioa = "-"
        
        if level == "COMMAND" or level == "WRITE":
            direction = "TX"
            category = "TX"
            # Try to extract IOA if present in message like "IOA 101"
            import re
            match = re.search(r'IOA\s+(\d+)', message)
            if match:
                ioa = match.group(1)
                
        elif "Received" in message or "Measurement" in message:
            direction = "RX"
            category = "RX"
            match = re.search(r'IOA\s+(\d+)', message)
            if match:
                ioa = match.group(1)
        
        elif "TESTFR" in message or "STARTDT" in message or "STOPDT" in message:
            category = "HEARTBEAT"
            direction = "TX" if "Sending" in message else "RX"
            type_name = "U-FRAME"
            
        elif level == "ERROR":
            category = "ERROR"
        elif level == "SUCCESS":
            category = "INFO"
            
        # Call the structured logger
        # We queue it similarly to before, or call directly if thread-safe
        # Since log_message is often called from thread via callbacks, we'll queue it
        
        self.message_queue.put({
            'type': 'new_log',
            'values': (timestamp, direction, type_name, ioa, message),
            'tags': (category,),
            'category': category
        })
        
    def log_traffic(self, timestamp, direction, type_name, ioa, details, tags, category):
        """Insert structured row into traffic monitor."""
        # Save exact data for filtering
        values = (timestamp, direction, type_name, ioa, details)
        self.traffic_data.append((values, tags, category))
        
        # Limit buffer size (e.g., last 1000 logs)
        if len(self.traffic_data) > 1000:
            self.traffic_data.pop(0)
            
        # Check filters before displaying
        if not self._should_show(category):
             return

        # Insert into tree
        item_id = self.traffic_tree.insert('', 'end', values=values, tags=tags)
        
        if self.auto_scroll.get():
            self.traffic_tree.see(item_id)
            
    def _should_show(self, category):
        """Check against active filters."""
        if category == 'RX' and not self.show_rx.get(): return False
        if category == 'TX' and not self.show_tx.get(): return False
        if category == 'HEARTBEAT' and not self.show_heartbeats.get(): return False
        return True
        
    def _refresh_traffic_view(self):
        """Re-populate tree based on current filters."""
        # Clear current view
        for item in self.traffic_tree.get_children():
            self.traffic_tree.delete(item)
            
        # Re-add matching items from buffer
        for values, tags, category in self.traffic_data:
            if self._should_show(category):
                self.traffic_tree.insert('', 'end', values=values, tags=tags)
                
    def _clear_traffic_log(self):
        """Clear traffic log buffer and view."""
        self.traffic_data = []
        for item in self.traffic_tree.get_children():
            self.traffic_tree.delete(item)
            
