    def _auto_reconnect_after_config_change(self):
        """Automatically disconnect and reconnect to re-register points after config change.
        
        This ensures that newly added IOA addresses are properly registered
        with the IEC 104 server.
        """
        # Check if currently connected
        was_connected = (self.connection_status == "CONNECTED" or 
                         (self.connection and self.connection.state == c104.ConnectionState.OPEN))
        
        if was_connected:
            self.log_message("Auto-reconnecting to register new points...", "INFO")
            
            # Disconnect
            self._stop_reconnect = True
            self._client_running = False
            
            if self.flow_control_manager:
                self.flow_control_manager.stop()
            if self.time_sync_manager:
                self.time_sync_manager.stop()
            if self.client:
                try:
                    self.client.stop()
                except Exception:
                    pass
            
            # Small delay to ensure clean disconnect
            self.root.after(500, self._reconnect_after_delay)
        else:
            # Not connected - just connect now
            self.log_message("Connecting to register new points...", "INFO")
            self._stop_reconnect = False
            self._client_running = False
            self.start_iec104_client()
    
    def _reconnect_after_delay(self):
        """Reconnect after a brief delay (called from _auto_reconnect_after_config_change)."""
        self.update_connection_status("DISCONNECTED")
