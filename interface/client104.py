@dataclass
class QOS:
    """
    Qualifier of Set-point command (QOS) - 1 byte.
    
    Bit structure:
    - Bits 0-6: QL (Qualifier Level, 0 = default)
    - Bit 7: S/E (Select/Execute flag)
        - 0 = Execute
        - 1 = Select
    """
    select: bool = False  # S/E bit: True=Select, False=Execute
    ql: int = 0           # Qualifier level (0-127)
    
    def encode(self) -> int:
        """Encode QOS to a single byte."""
        qos_byte = self.ql & 0x7F  # Bits 0-6
        if self.select:
            qos_byte |= 0x80       # Bit 7 = 1 for Select
        return qos_byte
    
    @staticmethod
    def decode(byte_val: int) -> 'QOS':
        """Decode QOS from a single byte."""
        return QOS(
            select=bool(byte_val & 0x80),
            ql=byte_val & 0x7F
        )


class SetPointCommandASDU:
    """
    ASDU structure for C_SE_NC_1 (Set-point command, short floating point).
    TypeID: 50
    
    Structure (8 bytes for information object):
    ┌─────────────────────────────────────────────────────────────────┐
    │  IOA (3 bytes)  │  Value (4 bytes, IEEE 754)  │  QOS (1 byte)   │
    └─────────────────────────────────────────────────────────────────┘
    
    IOA: Information Object Address (24-bit, little-endian)
    Value: IEEE 754 single-precision floating point (32-bit, little-endian)
    QOS: Qualifier of Set-point (8-bit)
        - Bits 0-6: QL (qualifier level)
        - Bit 7: S/E (0=Execute, 1=Select)
    """
    TYPE_ID = 50  # C_SE_NC_1
    
    @staticmethod
    def encode_value(value: float) -> bytes:
        """Encode float value to IEEE 754 (4 bytes, little-endian)."""
        return struct.pack('<f', value)
    
    @staticmethod
    def decode_value(data: bytes) -> float:
        """Decode IEEE 754 bytes to float."""
        if len(data) != 4:
            raise ValueError(f"Invalid IEEE 754 length: {len(data)}")
        return struct.unpack('<f', data)[0]
    
    @staticmethod
    def encode_ioa(ioa: int) -> bytes:
        """Encode IOA to 3 bytes (little-endian)."""
        return struct.pack('<I', ioa)[:3]  # Take lower 3 bytes
    
    @staticmethod
    def decode_ioa(data: bytes) -> int:
        """Decode 3-byte IOA."""
        if len(data) != 3:
            raise ValueError(f"Invalid IOA length: {len(data)}")
        return struct.unpack('<I', data + b'\x00')[0]
    
    @staticmethod
    def build_information_object(ioa: int, value: float, qos: QOS) -> bytes:
        """
        Build complete information object for C_SE_NC_1.
        
        Args:
            ioa: Information Object Address (0-16777215)
            value: Setpoint value as IEEE 754 float
            qos: Qualifier of Set-point
            
        Returns:
            8 bytes: IOA (3) + Value (4) + QOS (1)
        """
        ioa_bytes = SetPointCommandASDU.encode_ioa(ioa)
        value_bytes = SetPointCommandASDU.encode_value(value)
        qos_byte = bytes([qos.encode()])
        
        return ioa_bytes + value_bytes + qos_byte
    
    @staticmethod
    def parse_information_object(data: bytes) -> tuple[int, float, QOS]:
        """Parse information object from bytes."""
        if len(data) != 8:
            raise ValueError(f"Invalid C_SE_NC_1 data length: {len(data)}")
            
        ioa = SetPointCommandASDU.decode_ioa(data[0:3])
        value = SetPointCommandASDU.decode_value(data[3:7])
        qos = QOS.decode(data[7])
        
        return ioa, value, qos


