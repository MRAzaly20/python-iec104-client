    def process_queue(self):
        """Process message queue"""
        try:
            # Process messages
            while not self.message_queue.empty():
                item = self.message_queue.get_nowait()
                
                # Handle new structured log message
                if isinstance(item, dict) and item.get('type') == 'new_log':
                    self.log_traffic(
                        timestamp=item['values'][0],
                        direction=item['values'][1],
                        type_name=item['values'][2],
                        ioa=item['values'][3],
                        details=item['values'][4],
                        tags=item['tags'],
                        category=item['category']
                    )
                # Handle legacy tuple format (backward compatibility if any other threads queue directly)
                elif isinstance(item, tuple) and len(item) == 2:
                    # Best effort conversion to new format
                    timestamp = datetime.now().strftime("%H:%M:%S")
                    message, level = item
                    self.log_traffic(timestamp, "--", level, "-", message, (level,), "INFO")
            
            # Process commands
            while not self.command_queue.empty():
                command = self.command_queue.get_nowait()
                if command[0] == "ON":
                    self.command_status.config(text="ON command sent", foreground="green")
                elif command[0] == "OFF":
                    self.command_status.config(text="OFF command sent", foreground="green")
                elif command[0] == "READ_ALL":
                    self.command_status.config(text="Reading points...", foreground="blue")
                    
        except queue.Empty:
            pass
        
        # Schedule next queue processing
        self.root.after(100, self.process_queue)
    
    def async_exception_handler(self, task: asyncio.Future):
        try:
            task.result()
        except (asyncio.CancelledError, concurrent.futures.CancelledError):
            return
        except Exception as e:
            self.log_message(f"Error in async task: {str(e)}", "ERROR")
            logging.error(f"Unhandled exception in coroutine:", exc_info=True)
    
    async def async_measurement(self, point: c104.Point, message: c104.IncomingMessage) -> None:
        """Handle incoming measurements"""
        try:
            # Extract value
            if hasattr(point.info, 'value'):
                value = point.info.value
            else:
                value = getattr(point, 'value', 'N/A')
                
            # Extract quality
            if hasattr(point.info, 'quality'):
                quality = "GOOD" if point.info.quality.is_good else "BAD"
            else:
                quality = "UNKNOWN"
                
            # Extract timestamp
            if hasattr(point.info, 'processed_at') and point.info.processed_at:
                timestamp = point.info.processed_at.strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
            else:
                timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S.%f")[:-3]
            
            # Queue update for GUI thread
            self.message_queue.put((f"Received {point.type} on IOA {point.io_address}: {value}\n", "SUCCESS"))
            
            # Update GUI from main thread
            self.root.after(0, self.update_point_display, point.io_address, value, quality, timestamp)
            
        except Exception as e:
            self.message_queue.put((f"Error processing point {point.io_address}: {str(e)}\n", "ERROR"))
    
    def on_receive_point(self, point: c104.Point, previous_info: c104.Information,
                        message: c104.IncomingMessage, loop: asyncio.AbstractEventLoop) -> c104.ResponseState:
        """Synchronous callback for point reception"""
        try:
            # Reset t3 timer - APDU received from server
            if self.flow_control_manager:
                self.flow_control_manager.on_apdu_received()
            
            future = asyncio.run_coroutine_threadsafe(self.async_measurement(point, message), loop)
            future.add_done_callback(self.async_exception_handler)
        except Exception as e:
            self.root.after(0, self.log_message, f"Error in receive callback: {str(e)}", "ERROR")
        
        return c104.ResponseState.SUCCESS
    
    def send_command_async(self, command_point, state):
        """Send command to server"""
        try:
            # Perbaikan: Akses enum dengan benar
            if state == "ON":
                cmd_state = c104.Double.ON
            elif state == "OFF":
                cmd_state = c104.Double.OFF
            else:
                raise ValueError(f"Invalid command state: {state}")
            
            # Buat command info
            command_point.info = c104.DoubleCmd(
                state=cmd_state,
                qualifier=c104.Qoc.LONG_PULSE
            )
            
            # Kirim command
            if command_point.transmit(cause=c104.Cot.ACTIVATION):
                self.root.after(0, self.log_message, f"{state} command sent successfully", "SUCCESS")
                #self.root.after(0, lambda: self.command_status.config(text=f"{state} command SUCCESS", foreground="green"))
            else:
                self.root.after(0, self.log_message, f"Failed to send {state} command", "ERROR")
                #self.root.after(0, lambda: self.command_status.config(text=f"{state} command FAILED", foreground="red"))
                
        except Exception as e:
            self.root.after(0, self.log_message, f"Error sending {state} command: {str(e)}", "ERROR")
            #self.root.after(0, lambda: self.command_status.config(text=f"{state} command ERROR", foreground="red"))
    
    async def write_point_async(self, ioa, value, point_type):
        """Write value to point"""
        try:
            if ioa not in self.monitoring_points:
                # Create point if not exists
                point = self.station.add_point(io_address=ioa, type=getattr(c104.Type, point_type))
                self.monitoring_points[ioa] = point
            else:
                point = self.monitoring_points[ioa]
            
            # Set value based on point type
            if point_type == 'M_SP_NA_1':
                point.info = c104.SingleInfo(
                    value=bool(value),
                    quality=c104.Quality.Substituted
                )
            elif point_type == 'M_DP_NA_1':
                point.info = c104.DoublePointInfo(
                    value=value,
                    quality=c104.Quality.GOOD
                )
            elif point_type == 'M_ME_NA_1':  # Normalized
                normalized_value = max(-1.0, min(1.0, float(value)))
                point.info = c104.MeasuredValueNormalizedInfo(
                    value=normalized_value,
                    quality=c104.Quality.GOOD
                )
            elif point_type == 'M_ME_NB_1':  # Scaled
                scaled_value = max(-32768, min(32767, int(float(value))))
                point.info = c104.MeasuredValueScaledInfo(
                    value=scaled_value,
                    quality=c104.Quality.GOOD
                )
            elif point_type == 'M_ME_NC_1':  # Short Float
                point.info = c104.MeasuredValueShortInfo(
                    value=float(value),
                    quality=c104.Quality.GOOD
                )
            elif point_type == 'M_IT_NA_1':  # Counter
                counter_value = max(0, int(value))
                point.info = c104.IntegratedTotalsInfo(
                    value=counter_value,
                    quality=c104.Quality.GOOD
                )
            
            # Transmit the value
            if point.transmit():
                self.root.after(0, self.log_message, f"Write to IOA {ioa} successful: {value}", "SUCCESS")
            else:
                self.root.after(0, self.log_message, f"Failed to write to IOA {ioa}", "ERROR")
                
        except Exception as e:
            self.root.after(0, self.log_message, f"Error writing to IOA {ioa}: {str(e)}", "ERROR")
    
    async def read_all_points_async(self, points_dict):
        """Read all points"""
        try:
            self.root.after(0, self.log_message, "Reading all points...", "COMMAND")
            
            for name, point in points_dict.items():
                if point.read():
                    self.root.after(0, self.log_message, f"Read SUCCESS: {name} = {point.value}", "SUCCESS")
                else:
                    self.root.after(0, self.log_message, f"Read FAILED: {name}", "ERROR")
                await asyncio.sleep(0.1)
                
            self.root.after(0, lambda: self.command_status.config(text="Read completed", foreground="green"))
            
        except Exception as e:
            self.root.after(0, self.log_message, f"Error reading points: {str(e)}", "ERROR")
    
    async def iec104_client_main(self):
        """Main IEC 104 client logic with auto-reconnection support."""
        loop = asyncio.get_event_loop()
        self._client_running = True
        
        while self._client_running and not self._stop_reconnect:
            # Flag for connection timeout from FlowControl
            connection_timeout_flag = [False]
            
            def send_testfr_callback() -> bool:
                """Callback to send TESTFR_ACT frame."""
                try:
                    if self.connection and self.connection.state == c104.ConnectionState.OPEN:
                        self.root.after(0, self.log_message, "[TESTFR] Sending TESTFR_ACT", "COMMAND")
                        return True
                    return False
                except Exception as e:
                    self.root.after(0, self.log_message, f"[TESTFR] Error: {e}", "ERROR")
                    return False
            
            def connection_timeout_callback():
                """Callback when connection timeout (t1) occurs."""
                connection_timeout_flag[0] = True
                self.root.after(0, self.log_message, "[FlowControl] Connection timeout - closing", "ERROR")
                self.root.after(0, self.update_connection_status, "TIMEOUT")
            
            try:
                # --- Client Setup ---
                self.client = c104.Client()
                self.connection = self.client.add_connection(
                    ip=self.server_ip, 
                    port=self.server_port, 
                    init=c104.Init.ALL
                )
                self.station = self.connection.add_station(common_address=47)
                
                # --- Initialize Flow Control Manager ---
                self.flow_control_manager = FlowControlManager(
                    config=self.flow_config,
                    on_send_testfr=send_testfr_callback,
                    on_connection_timeout=connection_timeout_callback,
                    on_log=self.log_message
                )
                
                # Log connection info
                self.root.after(0, self.log_message, 
                    f"Connecting to {self.server_ip}:{self.server_port}...", 
                    "COMMAND"
                )
                self.root.after(0, self.log_message, 
                    f"[FlowControl] Config: k={self.flow_config.k}, w={self.flow_config.w}, "
                    f"t1={self.flow_config.t1}s, t2={self.flow_config.t2}s, t3={self.flow_config.t3}s", 
                    "INFO"
                )
                
                # Update GUI status
                self.root.after(0, self.update_connection_status, "CONNECTING")
                
                # Dictionary untuk menyimpan semua point
                self.monitoring_points = {}
                
                # --- Setup Points from StationConfig ---
                self.root.after(0, self.log_message, 
                    f"Registering {len(self.station_config.get_all_points())} points from config...",
                    "INFO"
                )
                
                for group in self.station_config.groups:
                    for data_point in group.points:
                        try:
                            # Get c104 type from AsduType
                            c104_type = data_point.asdu_type.to_c104_type()
                            if c104_type is None:
                                self.root.after(0, self.log_message,
                                    f"Unknown type {data_point.asdu_type.name} for IOA {data_point.ioa}",
                                    "ERROR"
                                )
                                continue
                            
                            # Add point to station
                            point = self.station.add_point(
                                io_address=data_point.ioa,
                                type=c104_type
                            )
                            
                            # Register receive callback for monitoring points
                            if data_point.asdu_type.name.startswith('M_'):
                                point.on_receive(
                                    callable=functools.partial(self.on_receive_point, loop=loop)
                                )
                            
                            # Store references
                            self.monitoring_points[data_point.ioa] = point
                            data_point.c104_point = point
                            
                        except Exception as e:
                            self.root.after(0, self.log_message,
                                f"Error registering IOA {data_point.ioa}: {e}",
                                "ERROR"
                            )
                
                self.root.after(0, self.log_message,
                    f"Registered {len(self.monitoring_points)} points successfully",
                    "SUCCESS"
                )
                
                # --- Start Client ---
                self.client.start()
                
                # Wait for connection with timeout
                connection_wait_start = time.monotonic()
                connection_timeout = 30.0  # 30 second connection timeout
                
                while self.connection.state != c104.ConnectionState.OPEN:
                    if self._stop_reconnect or not self._client_running:
                        break
                    if time.monotonic() - connection_wait_start > connection_timeout:
                        raise ConnectionError("Connection timeout - server not responding")
                    await asyncio.sleep(0.5)
                
                if self._stop_reconnect or not self._client_running:
                    break
                
                # Reset reconnect counter on successful connection
                self.reconnect_attempt_count = 0
                
                # Update GUI status
                self.root.after(0, self.update_connection_status, "CONNECTED")
                self.root.after(0, self.update_connection_buttons, True)
                self.root.after(0, self.log_message, 
                    f"Connected to IEC 104 server at {self.server_ip}:{self.server_port}", 
                    "SUCCESS"
                )
                
                # --- Start Flow Control Timer ---
                self.flow_control_manager.start(loop)
                
                # --- Start Time Sync ---
                # We assume self.station is valid here
                self.time_sync_manager = TimeSyncManager(
                    config=self.time_sync_config,
                    station=self.station,
                    on_log=lambda msg, level: self.root.after(0, self.log_message, msg, level)
                )
                self.time_sync_manager.start_auto_sync(loop)
                
                # Process commands while connected
                while (self.connection.state == c104.ConnectionState.OPEN 
                       and not connection_timeout_flag[0]
                       and self._client_running
                       and not self._stop_reconnect):
                    try:
                        # print("client status: ", self.connection.state)
                        #print("Processing command queue...")
                        if not self.command_queue.empty():
                            cmd = self.command_queue.get_nowait()
                            print(f"Processing command: {cmd}")
                            if cmd[0] == "COMMAND":
                                # cmd format: ("COMMAND", ioa, state)
                                cmd_ioa = cmd[1]
                                cmd_state = cmd[2]
                                print(f"Processing command: IOA {cmd_ioa}, State {cmd_state}")
                                # Look up command point from monitoring_points
                                if cmd_ioa in self.monitoring_points:
                                    command_point = self.monitoring_points[cmd_ioa]
                                    print(f"Sending command to IOA {cmd_ioa} with state {cmd_state} to point {command_point}")  
                                    self.send_command_async(command_point, cmd_state)
                                else:
                                    self.root.after(0, self.log_message, 
                                        f"Command point IOA {cmd_ioa} not found!", "ERROR")
                            elif cmd[0] == "READ_ALL":
                                await self.read_all_points_async(self.monitoring_points)
                            elif cmd[0] == "WRITE_SINGLE":
                                await self.write_point_async(cmd[1], cmd[2], 'M_SP_NA_1')
                            elif cmd[0] == "WRITE_DOUBLE":
                                await self.write_point_async(cmd[1], cmd[2], 'M_DP_NA_1')
                            elif cmd[0] == "WRITE_ANALOG":
                                await self.write_point_async(cmd[1], cmd[2], cmd[3])
                            elif cmd[0] == "WRITE_COUNTER":
                                await self.write_point_async(cmd[1], cmd[2], 'M_IT_NA_1')
                            elif cmd[0] == "SYNC_TIME":
                                if self.time_sync_manager:
                                    await self.time_sync_manager.send_clock_sync()
                    except queue.Empty:
                        pass
                    
                    await asyncio.sleep(0.1)
                
                # --- Cleanup Flow Control ---
                if self.flow_control_manager:
                    self.flow_control_manager.stop()
                    self.flow_control_manager = None

                # --- Cleanup Time Sync ---
                if self.time_sync_manager:
                    self.time_sync_manager.stop()
                    self.time_sync_manager = None
                
                # Determine disconnect reason
                if self._stop_reconnect:
                    self.root.after(0, self.update_connection_status, "DISCONNECTED")
                    self.root.after(0, self.log_message, "Disconnected by user request", "INFO")
                    break
                elif connection_timeout_flag[0]:
                    self.root.after(0, self.update_connection_status, "TIMEOUT", "TESTFR timeout")
                    self.root.after(0, self.log_message, "Connection closed due to TESTFR timeout", "ERROR")
                else:
                    self.root.after(0, self.update_connection_status, "DISCONNECTED")
                    self.root.after(0, self.log_message, "Connection to server lost", "ERROR")
                
            except Exception as e:
                if self.flow_control_manager:
                    self.flow_control_manager.stop()
                    self.flow_control_manager = None
                self.root.after(0, self.log_message, f"IEC 104 client error: {str(e)}", "ERROR")
                self.root.after(0, self.update_connection_status, "ERROR", str(e))
            
            finally:
                # Cleanup client
                if self.client:
                    try:
                        self.client.stop()
                    except Exception:
                        pass
                    self.client = None
                self.connection = None
                self.station = None
            
            # --- Auto-Reconnect Logic ---
            if (self.auto_reconnect_enabled 
                and self._client_running 
                and not self._stop_reconnect):
                
                self.reconnect_attempt_count += 1
                
                # Check max attempts (0 = unlimited)
                if self.max_reconnect_attempts > 0 and self.reconnect_attempt_count >= self.max_reconnect_attempts:
                    self.root.after(0, self.log_message, 
                        f"Max reconnect attempts ({self.max_reconnect_attempts}) reached. Stopping.", 
                        "ERROR"
                    )
                    break
                
                self.root.after(0, self.update_connection_status, "RECONNECTING")
                self.root.after(0, self.log_message, 
                    f"[Reconnect] Attempt #{self.reconnect_attempt_count} in {self.reconnect_interval}s...", 
                    "RECONNECT"
                )
                
                # Wait before reconnecting
                for _ in range(int(self.reconnect_interval * 10)):
                    if self._stop_reconnect or not self._client_running:
                        break
                    await asyncio.sleep(0.1)
            else:
                break
        
        # Final cleanup and UI update
        self._client_running = False
        self.root.after(0, self.update_connection_buttons, False)
    
    def start_iec104_client(self):
        """Start IEC 104 client in a separate thread"""
        # Create and start the thread
        thread = threading.Thread(target=self.run_iec104_client)
        thread.daemon = True
        thread.start()

    def run_iec104_client(self):
        """Run IEC 104 client in separate thread."""
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        try:
            loop.run_until_complete(self.iec104_client_main())
        finally:
            loop.close()
    
    def run(self):
        """Start the GUI"""
        self.root.protocol("WM_DELETE_WINDOW", self.on_closing)
        self.root.mainloop()
    
    def on_closing(self):
        """Handle window closing"""
        self.log_message("Application closing...", "INFO")
        self.root.destroy()
    
